function buildAddress(info: BusinessInfo): string {
  const parts = [
    info.postalCode ? `〒${info.postalCode}` : null,
    info.prefecture,
    info.city,
    info.streetAddress,
    info.buildingName,
  ].filter((v): v is string => Boolean(v));

  return parts.length > 0 ? parts.join(" ") : PLACEHOLDER.address;
}

function formatLastUpdatedJa(date: Date): string {
  const formatter = new Intl.DateTimeFormat("ja-JP", {
    year: "numeric",
    month: "long",
    day: "numeric",
    timeZone: "Asia/Tokyo",
  });
  return formatter.format(date);
}

/**
 * テンプレート本文中のプレースホルダーを、Settings から取得した事業者情報および
 * 現在日時で置換する。未設定のフィールドはプレースホルダーが残り、管理者への
 * 入力プロンプトとして機能する。
 *
 * 同一プレースホルダーがテンプレート内に複数回現れる場合に備えて `replaceAll` を使用する。
 */
export function applyBusinessInfo(content: string, info: BusinessInfo): string {
  const replacements: ReadonlyArray<readonly [string, string]> = [
    [PLACEHOLDER.businessName, info.businessName ?? PLACEHOLDER.businessName],
    [
      PLACEHOLDER.representativeName,
      info.representativeName ?? PLACEHOLDER.representativeName,
    ],
    [
      PLACEHOLDER.invoiceNumber,
      info.invoiceNumber ?? PLACEHOLDER.invoiceNumber,
    ],
    [PLACEHOLDER.address, buildAddress(info)],
    [PLACEHOLDER.email, info.email ?? PLACEHOLDER.email],
    [PLACEHOLDER.phoneNumber, info.phoneNumber ?? PLACEHOLDER.phoneNumber],
    [PLACEHOLDER.lastUpdated, formatLastUpdatedJa(new Date())],
  ];

  let result = content;
  for (const [placeholder, value] of replacements) {
    result = result.replaceAll(placeholder, value);
  }

  return result;
}
